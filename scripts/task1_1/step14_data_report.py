import os, json, glob
from datetime import date
import pandas as pd

OUT_DIR = "data/processed/crisis"
REPORT  = f"{OUT_DIR}/DATA_REPORT.md"
OUR_CATEGORIES = ["suicidal_ideation","self_harm","violence",
                  "anxiety_crisis","substance_abuse","risk_taking","no_crisis"]

def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    lines = [f"# Crisis Classifier Data Report",
             f"Generated: {date.today()}  |  Task 1.1  |  Owner: Eman (P1), Rania (P2)","","---","",
             "## 1. Sources","","|Source|Rows|Licence|","|---|---|---|"]
    sources = {"Arnaiz-Rodriguez 2026":"data/raw/arnaiz_mapped.jsonl",
               "SHINES":"data/raw/shines_extracted.jsonl",
               "CRADLE 10% train":"data/raw/cradle_train_10pct.jsonl"}
    for name, path in sources.items():
        n = len(pd.read_json(path,lines=True)) if os.path.exists(path) else "not found"
        lines.append(f"|{name}|{n}|CC BY-NC / TBD|")
    hf_n = sum(len(pd.read_json(f,lines=True)) for f in glob.glob("data/raw/hf_labelled/*.jsonl"))
    lines += [f"|HF corpus (LLM-labelled)|{hf_n}|Various|","","## 2. Final Splits",""]
    sfile = f"{OUT_DIR}/split_summary.json"
    if os.path.exists(sfile):
        s = json.load(open(sfile))
        lines += [f"Split: {s.get('split','70/15/15')}  Total: {s.get('total','?')}","",
                  "|Category|Train|Val|Test|","|---|---|---|---|"]
        for cat in OUR_CATEGORIES:
            tr=s.get("train_dist",{}).get(cat,0)
            va=s.get("val_dist",{}).get(cat,0)
            te=s.get("test_dist",{}).get(cat,0)
            lines.append(f"|{cat}|{tr}|{va}|{te}|")
    else:
        lines.append("_Run step12 first._")
    lines += ["","---",f"_Generated by scripts/task1_1/step14_data_report.py_"]
    report = "\n".join(lines)
    with open(REPORT,"w") as f: f.write(report)
    print(report)
    print(f"\n[step14] Report → {REPORT}")
    print("[step14] ✓ Task 1.1 COMPLETE")

if __name__ == "__main__":
    main()
